"""Street hierarchy of the game map: every road edge gets a class from the real traffic heat.

``game/streets.png`` is the alpha heat of the taxi traces (1 pixel = 1 map unit). The mean heat
along an edge of ``game/roads.json`` ranks it: the busiest edges become arteries (``main``), the
next band ``mid`` streets and the rest quiet side streets (``minor``). The result is decoration
of the game model: ``game/src/js/36_streets_data.js`` (``PG.streets``), polylines in whole
metres of the map frame.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROADS_DEFAULT = Path("game/roads.json")
STREETS_DEFAULT = Path("game/streets.png")
DATA_DEFAULT = Path("game/game_data.json")
OUT_DEFAULT = Path("game/src/js/36_streets_data.js")
HEADER = "// generated by pipeline/roadclass.py, do not edit\n"
SAMPLE_M = 20.0  # heat sampling step along an edge, metres
MAIN_SHARE = 0.10  # share of the total road length that becomes arteries
MID_SHARE = 0.28  # share of the total road length that becomes mid streets
MAIN, MID, MINOR = 0, 1, 2

Polyline = list[tuple[float, float]]


def edge_lines(roads: dict[str, object]) -> list[Polyline]:
    """Rebuild every edge of the road graph as a polyline in metres.

    Args:
        roads: Parsed ``roads.json`` (``unit_m``, ``nodes`` flat, ``edges`` of ``[a, b, mid]``).

    Returns:
        One polyline per edge, end nodes included.
    """
    u = float(roads["unit_m"])  # type: ignore[arg-type]
    nodes = roads["nodes"]
    out: list[Polyline] = []
    for a, b, mid in roads["edges"]:  # type: ignore[attr-defined]
        pts = [(nodes[2 * a] * u, nodes[2 * a + 1] * u)]  # type: ignore[index]
        pts += [(mid[i] * u, mid[i + 1] * u) for i in range(0, len(mid) - 1, 2)]
        pts.append((nodes[2 * b] * u, nodes[2 * b + 1] * u))  # type: ignore[index]
        out.append(pts)
    return out


def line_length(line: Polyline) -> float:
    """Length of a polyline.

    Args:
        line: Points in metres.

    Returns:
        Metres.
    """
    return sum(math.hypot(b[0] - a[0], b[1] - a[1]) for a, b in zip(line, line[1:], strict=False))


def mean_heat(line: Polyline, heat: np.ndarray, unit_m: float) -> float:
    """Mean of the heat image along a polyline (3x3 maximum around each sample).

    Args:
        line: Points in metres.
        heat: Heat image, rows are y, values 0..255.
        unit_m: Metres per image pixel.

    Returns:
        The mean heat, 0 for a degenerate line.
    """
    vals: list[float] = []
    for a, b in zip(line, line[1:], strict=False):
        n = max(1, int(math.hypot(b[0] - a[0], b[1] - a[1]) / SAMPLE_M))
        for k in range(n):
            x = int((a[0] + (b[0] - a[0]) * k / n) / unit_m)
            y = int((a[1] + (b[1] - a[1]) * k / n) / unit_m)
            win = heat[max(y - 1, 0) : y + 2, max(x - 1, 0) : x + 2]
            vals.append(float(win.max()) if win.size else 0.0)
    return sum(vals) / len(vals) if vals else 0.0


def classify(roads_path: Path, streets_path: Path, unit_m: float) -> list[tuple[int, Polyline]]:
    """Give every road edge a class by the length-weighted rank of its mean heat.

    Args:
        roads_path: ``roads.json``.
        streets_path: ``streets.png`` (alpha channel is the heat).
        unit_m: Metres per pixel of the streets image (the game data unit).

    Returns:
        ``(class, polyline)`` per edge, class one of ``MAIN``, ``MID``, ``MINOR``.
    """
    roads = json.loads(roads_path.read_text(encoding="utf-8"))
    heat = np.array(Image.open(streets_path).convert("RGBA"))[..., 3]
    lines = edge_lines(roads)
    scored = sorted(
        ((mean_heat(ln, heat, unit_m), i, line_length(ln)) for i, ln in enumerate(lines)),
        reverse=True,
    )
    total = sum(s[2] for s in scored) or 1.0
    cls = [MINOR] * len(lines)
    acc = 0.0
    for _, i, ln in scored:
        share = acc / total
        cls[i] = MAIN if share < MAIN_SHARE else MID if share < MAIN_SHARE + MID_SHARE else MINOR
        acc += ln
    return list(zip(cls, lines, strict=True))


def build(roads_path: Path, streets_path: Path, data_path: Path) -> dict[str, object]:
    """Compute the street layer.

    Args:
        roads_path: ``roads.json``.
        streets_path: ``streets.png``.
        data_path: ``game_data.json`` (for the pixel size ``unit_m``).

    Returns:
        JSON-ready dict: ``main``, ``mid``, ``minor`` lists of flat whole-metre polylines.
    """
    unit_m = float(json.loads(data_path.read_text(encoding="utf-8"))["unit_m"])
    groups: dict[str, list[list[int]]] = {"main": [], "mid": [], "minor": []}
    for c, ln in classify(roads_path, streets_path, unit_m):
        groups[("main", "mid", "minor")[c]].append([round(v) for p in ln for v in p])
    return {"source": "road graph ranked by taxi-trace heat", **groups}


def main(argv: list[str] | None = None) -> int:
    """Command line entry point.

    Args:
        argv: Arguments (default ``sys.argv[1:]``).

    Returns:
        0 on success, 1 when an input cannot be read.
    """
    ap = argparse.ArgumentParser(description="Write the street hierarchy layer for the game")
    ap.add_argument("--roads", type=Path, default=ROADS_DEFAULT)
    ap.add_argument("--streets", type=Path, default=STREETS_DEFAULT)
    ap.add_argument("--data", type=Path, default=DATA_DEFAULT)
    ap.add_argument("--out", type=Path, default=OUT_DEFAULT)
    args = ap.parse_args(argv)
    try:
        layer = build(args.roads, args.streets, args.data)
    except (OSError, KeyError, ValueError) as err:
        print(f"roadclass error: {err}", file=sys.stderr)
        return 1
    body = json.dumps(layer, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    args.out.write_bytes(f"{HEADER}window.PG = window.PG || {{}};\nPG.streets = {body};\n".encode())
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
