"""Invented, rule-based traffic jams for the game map (GAME MODEL rules, not UCI data).

The jams are fixed by rule so the player can learn them: the same streets are slow in the same
hours every day. Morning (08-10) and evening (17-19) rush: the bridges Luis I and Arrabida and
the main streets of Baixa and Boavista; lunch (12-14): light jams in Baixa; night: none.
A red jam slows cars to ``RED_MUL`` of their speed, a yellow one to ``YELLOW_MUL``; a window
ramps in over its first ``RAMP_IN_S`` seconds and out over its last ``RAMP_OUT_S`` seconds.
Streets come from ``game/roads.json`` ranked by :mod:`pipeline.roadclass`; the result is
``game/src/js/43_traffic_data.js`` (``PG.trafficData``), read by ``44_traffic.js``.
Positions are whole metres of the map frame.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from collections.abc import Callable
from pathlib import Path

from pipeline import basemap, geo, roadclass
from pipeline.basemap import Pt, inside_poly
from pipeline.landmarks import DATA_DEFAULT, map_size_m

OUT_DEFAULT = Path("game/src/js/43_traffic_data.js")
SOURCE = "invented rule-based jams, same every day, not from the UCI taxi data"
HEADER = "// generated by pipeline/traffic.py, do not edit\n"
WINDOWS_H = ((8, 10), (12, 14), (17, 19))  # jam windows (start hour, end hour), hour of day
NONE, YELLOW, RED = 0, 1, 2  # jam level of a street in a window
RED_MUL = 0.5  # speed factor in a red jam
YELLOW_MUL = 0.75  # speed factor in a yellow jam
RAMP_IN_S = 1200  # seconds a window needs to reach full strength
RAMP_OUT_S = 600  # seconds a window needs to fade out at its end
BRIDGES = ("Ponte Luís I", "Ponte da Arrábida")  # bridges that jam
APPROACH_M = 260.0  # road kept around a jammed bridge, metres from the deck centre beyond its half
STEP_M = 10.0  # resampling step of street polylines, metres
SIMPLIFY_M = 3.0  # RDP tolerance of the output polylines, metres
MIN_PIECE_M = 20.0  # shorter street pieces are dropped, metres
# levels per window (morning, lunch, evening) of each jammed feature
BRIDGE_LEVELS = (RED, NONE, RED)
BAIXA_LEVELS = (RED, YELLOW, RED)
BOAVISTA_LEVELS = (YELLOW, NONE, YELLOW)


def resample(line: list[Pt], step: float = STEP_M) -> list[Pt]:
    """Insert points so no gap of a polyline is longer than ``step``.

    Args:
        line: Points in metres.
        step: Largest gap, metres.

    Returns:
        The denser polyline (same shape).
    """
    out: list[Pt] = [line[0]]
    for a, b in zip(line, line[1:], strict=False):
        n = max(1, math.ceil(math.hypot(b[0] - a[0], b[1] - a[1]) / step))
        out += [
            (a[0] + (b[0] - a[0]) * k / n, a[1] + (b[1] - a[1]) * k / n) for k in range(1, n + 1)
        ]
    return out


def pieces(line: list[Pt], keep: Callable[[Pt], bool]) -> list[list[Pt]]:
    """Cut a polyline into the runs of points that satisfy a predicate.

    Args:
        line: Points in metres.
        keep: True for points that stay.

    Returns:
        Runs at least ``MIN_PIECE_M`` long, simplified.
    """
    runs: list[list[Pt]] = []
    cur: list[Pt] = []
    for p in resample(line):
        if keep(p):
            cur.append(p)
        else:
            runs.append(cur)
            cur = []
    runs.append(cur)
    return [
        geo.rdp(r, SIMPLIFY_M)
        for r in runs
        if len(r) > 1 and roadclass.line_length(r) >= MIN_PIECE_M
    ]


def flat_m(line: list[Pt]) -> list[int]:
    """Flatten points to whole metres.

    Args:
        line: Points in metres.

    Returns:
        ``[x0, y0, x1, y1, ...]``.
    """
    return [round(v) for p in line for v in p]


def build(data_path: Path = DATA_DEFAULT) -> dict[str, object]:
    """Compute the jam layer.

    Args:
        data_path: ``game_data.json`` (map size and unit).

    Returns:
        JSON-ready dict: ``windows`` (hours), ``ramp`` (in, out seconds), ``mul`` per level and
        ``segs`` (``{"l": level per window, "p": flat polyline}``).
    """
    w, h = map_size_m(data_path)
    layer = basemap.build(data_path)
    edges = roadclass.classify(
        roadclass.ROADS_DEFAULT,
        roadclass.STREETS_DEFAULT,
        float(json.loads(data_path.read_text(encoding="utf-8"))["unit_m"]),
    )
    main = [ln for c, ln in edges if c == roadclass.MAIN]
    mid = [ln for c, ln in edges if c == roadclass.MID]
    segs: list[dict[str, object]] = []

    def add(line: list[Pt], levels: tuple[int, ...]) -> None:
        segs.append({"l": list(levels), "p": flat_m(line)})

    def poly(name: str) -> list[Pt]:
        d = next(d for d in layer["districts"] if d["name"] == name)  # type: ignore[attr-defined,union-attr]
        p = d["poly"]  # type: ignore[index]
        return [(p[i], p[i + 1]) for i in range(0, len(p), 2)]

    for name, levels in (("Baixa", BAIXA_LEVELS), ("Boavista", BOAVISTA_LEVELS)):
        area = poly(name)
        for ln in main:
            for run in pieces(ln, lambda p, a=area: inside_poly(p, a)):
                add(run, levels)
    for b in layer["bridges"]:  # type: ignore[attr-defined,union-attr]
        if b["name"] not in BRIDGES:
            continue
        x0, y0, x1, y1 = b["line"]
        add([(x0, y0), (x1, y1)], BRIDGE_LEVELS)
        cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
        reach = math.hypot(x1 - x0, y1 - y0) / 2 + APPROACH_M
        for ln in main + mid:
            for run in pieces(
                ln, lambda p, c=(cx, cy), r=reach: math.hypot(p[0] - c[0], p[1] - c[1]) <= r
            ):
                if all(0 <= x <= w and 0 <= y <= h for x, y in run):
                    add(run, BRIDGE_LEVELS)
    return {
        "source": SOURCE,
        "windows": [list(win) for win in WINDOWS_H],
        "ramp": [RAMP_IN_S, RAMP_OUT_S],
        "mul": {"1": YELLOW_MUL, "2": RED_MUL},
        "segs": segs,
    }


def render_js(layer: dict[str, object]) -> str:
    """Render the layer as the generated JS data file (deterministic).

    Args:
        layer: Result of :func:`build`.

    Returns:
        JS source with sorted keys and LF line ends.
    """
    body = json.dumps(layer, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return f"{HEADER}window.PG = window.PG || {{}};\nPG.trafficData = {body};\n"


def main(argv: list[str] | None = None) -> int:
    """Command line entry point.

    Args:
        argv: Arguments (default ``sys.argv[1:]``).

    Returns:
        0 on success, 1 when an input cannot be read.
    """
    ap = argparse.ArgumentParser(description="Write the jam layer for the game")
    ap.add_argument("--data", type=Path, default=DATA_DEFAULT)
    ap.add_argument("--out", type=Path, default=OUT_DEFAULT)
    args = ap.parse_args(argv)
    try:
        layer = build(args.data)
    except (OSError, KeyError, ValueError, StopIteration) as err:
        print(f"traffic error: {err}", file=sys.stderr)
        return 1
    args.out.write_bytes(render_js(layer).encode("utf-8"))
    print(f"wrote {args.out} ({len(layer['segs'])} segments)")  # type: ignore[arg-type]
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
