"""Porto landmarks for the map of the game (decoration of the GAME MODEL, CONTRACT section 1).

The places, their lon/lat and their silhouette kinds are hand-placed by us (approximate,
public knowledge). They are NOT derived from the UCI taxi data: the output says so in its
``source`` field. The module projects them with :mod:`pipeline.geo`, drops those outside the
map given by ``game/game_data.json``, picks a label spot for each so that no two labels (and no
label and another landmark) overlap, and writes ``game/src/js/41_landmarks_data.js``, which the
build inlines as ``PG.landmarks``. All positions are in metres of the map frame, label offsets
are in screen pixels around the landmark base, laid out for the reference zoom ``REF_K``.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import NamedTuple

from pipeline import geo

DATA_DEFAULT = Path("game/game_data.json")
OUT_DEFAULT = Path("game/src/js/41_landmarks_data.js")
SOURCE = "hand-placed game-model decoration, not from the UCI taxi data"
HEADER = "// generated by pipeline/landmarks.py, do not edit\n"

KINDS = (
    "tower", "bridge", "cathedral", "station", "bookshop", "hall",
    "palace", "museum", "square", "market", "houses",
)  # fmt: skip
SIDES = ("e", "w", "n", "s", "ne", "nw", "se", "sw")
REF_K = 0.3  # reference zoom, screen px per metre, used to lay the labels out
CHAR_PX = 5.8  # label font width per character, px (11 px system font)
LABEL_H = 14  # label box height, px
GLYPH = (-16.0, -34.0, 16.0, 6.0)  # silhouette box around the base point, px (x0, y0, x1, y1)
GAP = 3  # free space kept around every box, px

Box = tuple[float, float, float, float]


class Landmark(NamedTuple):
    """One hand-placed landmark."""

    id: str
    name: str
    label: str  # short text on the map
    kind: str
    lon: float
    lat: float
    tier: int  # 0 shown from far zoom, 1 only when zoomed in


LANDMARKS: tuple[Landmark, ...] = (
    Landmark("clerigos", "Torre dos Clérigos", "Clérigos", "tower", -8.6146, 41.1459, 0),
    Landmark("luis1", "Ponte Luís I", "Ponte Luís I", "bridge", -8.6093, 41.1399, 0),
    Landmark("ribeira", "Ribeira", "Ribeira", "houses", -8.6129, 41.1406, 1),
    Landmark("se", "Sé do Porto", "Sé", "cathedral", -8.6114, 41.1428, 1),
    Landmark("bento", "Estação de São Bento", "São Bento", "station", -8.6104, 41.1456, 0),
    Landmark("lello", "Livraria Lello", "Lello", "bookshop", -8.6149, 41.1468, 1),
    Landmark("casa", "Casa da Música", "Casa da Música", "hall", -8.6307, 41.1588, 0),
    Landmark("bolsa", "Palácio da Bolsa", "Bolsa", "palace", -8.6161, 41.1417, 1),
    Landmark("serralves", "Serralves", "Serralves", "museum", -8.6597, 41.1595, 0),
    Landmark("aliados", "Avenida dos Aliados", "Aliados", "square", -8.6112, 41.1487, 0),
    Landmark("bolhao", "Mercado do Bolhão", "Bolhão", "market", -8.6062, 41.1494, 1),
)


def map_size_m(data_path: Path = DATA_DEFAULT) -> tuple[float, float]:
    """Read the map size in metres from the game data (bounds in map units times unit_m).

    Args:
        data_path: ``game_data.json``.

    Returns:
        ``(width, height)`` in metres.
    """
    data = json.loads(data_path.read_text(encoding="utf-8"))
    unit = float(data["unit_m"])
    return data["bounds"][2] * unit, data["bounds"][3] * unit


def project(lm: Landmark) -> tuple[float, float]:
    """Project a landmark to map metres with the shared projection.

    Args:
        lm: The landmark.

    Returns:
        ``(x, y)`` in metres, rounded to whole metres.
    """
    x, y = geo.proj(lm.lon, lm.lat)
    return round(x), round(y)


def inside(pos: tuple[float, float], size: tuple[float, float]) -> bool:
    """Tell whether a map position lies inside the map rectangle.

    Args:
        pos: ``(x, y)`` metres.
        size: ``(width, height)`` metres.

    Returns:
        True when 0 <= x <= width and 0 <= y <= height.
    """
    return 0 <= pos[0] <= size[0] and 0 <= pos[1] <= size[1]


def label_box(side: str, width: float) -> Box:
    """Place a label box relative to the landmark base for one of eight sides.

    Args:
        side: One of ``SIDES``.
        width: Label width, px.

    Returns:
        Box ``(x0, y0, x1, y1)`` in px around the base point (0, 0).
    """
    x0, y0, x1, y1 = GLYPH
    h = LABEL_H
    mid = (y0 + y1) / 2 - h / 2
    xs = {"e": x1 + GAP, "w": x0 - GAP - width, "n": -width / 2, "s": -width / 2}
    ys = {"e": mid, "w": mid, "n": y0 - GAP - h, "s": y1 + GAP}
    if len(side) == 2:  # diagonals sit on the corners
        xs[side] = x1 - 4 if side[1] == "e" else x0 + 4 - width
        ys[side] = y0 - GAP - h if side[0] == "n" else y1 + GAP
    return xs[side], ys[side], xs[side] + width, ys[side] + h


def overlaps(a: Box, b: Box) -> bool:
    """Tell whether two boxes, each grown by GAP / 2, intersect.

    Args:
        a: First box.
        b: Second box.

    Returns:
        True when they overlap.
    """
    g = GAP / 2
    apart = a[2] + g <= b[0] - g or b[2] + g <= a[0] - g
    return not (apart or a[3] + g <= b[1] - g or b[3] + g <= a[1] - g)


def shifted(box: Box, x: float, y: float) -> Box:
    """Move a box by ``(x, y)``.

    Args:
        box: The box.
        x: Shift in x.
        y: Shift in y.

    Returns:
        The moved box.
    """
    return box[0] + x, box[1] + y, box[2] + x, box[3] + y


def place_labels(items: list[Landmark], pos: list[tuple[float, float]]) -> list[tuple[str, Box]]:
    """Choose a side for every label so no label overlaps another label or a silhouette.

    Landmarks are handled in list order; each takes the first free side of ``SIDES``. When no
    side is free the least overlapping one is kept (the tests assert this does not happen for
    the shipped list).

    Args:
        items: The landmarks, most important first.
        pos: Their map positions in metres, same order.

    Returns:
        ``(side, box)`` per landmark, the box in px relative to that landmark's base.
    """
    px = [(x * REF_K, y * REF_K) for x, y in pos]
    glyphs = [shifted(GLYPH, x, y) for x, y in px]
    placed: list[Box] = []
    out: list[tuple[str, Box]] = []
    for i, lm in enumerate(items):
        width = len(lm.label) * CHAR_PX + 6
        others = glyphs[:i] + glyphs[i + 1 :] + placed
        best = (len(others) + 1, "e", label_box("e", width))
        for side in SIDES:
            box = label_box(side, width)
            hits = sum(overlaps(shifted(box, *px[i]), o) for o in others)
            if hits < best[0]:
                best = (hits, side, box)
            if hits == 0:
                break
        out.append((best[1], best[2]))
        placed.append(shifted(best[2], *px[i]))
    return out


def build(data_path: Path = DATA_DEFAULT) -> dict[str, object]:
    """Compute the landmark layer.

    Args:
        data_path: ``game_data.json`` (for the map bounds).

    Returns:
        The JSON-ready dict: ``source``, ``kinds`` and ``items`` (id, name, label, kind, x, y,
        tier, lx, ly, align in px relative to the base).
    """
    size = map_size_m(data_path)
    kept = [(lm, project(lm)) for lm in LANDMARKS]
    kept = [(lm, p) for lm, p in kept if inside(p, size)]
    items = [lm for lm, _ in kept]
    pos = [p for _, p in kept]
    items_out = []
    for lm, p, (side, box) in zip(items, pos, place_labels(items, pos), strict=True):
        align = "l" if side in ("e", "ne", "se") else "r" if side in ("w", "nw", "sw") else "c"
        lx = box[0] if align == "l" else box[2] if align == "r" else (box[0] + box[2]) / 2
        items_out.append(
            {
                "id": lm.id, "name": lm.name, "label": lm.label, "kind": lm.kind,
                "x": p[0], "y": p[1], "tier": lm.tier,
                "lx": round(lx, 1), "ly": round(box[3] - 3, 1), "align": align,
            }
        )  # fmt: skip
    return {"source": SOURCE, "kinds": list(KINDS), "items": items_out}


def render_js(layer: dict[str, object]) -> str:
    """Render the layer as the generated JS data file.

    Args:
        layer: Result of :func:`build`.

    Returns:
        JS source, deterministic (sorted keys, LF).
    """
    body = json.dumps(layer, ensure_ascii=False, sort_keys=True, indent=1)
    return f"{HEADER}window.PG = window.PG || {{}};\nPG.landmarks = {body};\n"


def main(argv: list[str] | None = None) -> int:
    """Command line entry point.

    Args:
        argv: Arguments (default ``sys.argv[1:]``).

    Returns:
        0 on success, 1 when the data file cannot be read.
    """
    ap = argparse.ArgumentParser(description="Write the Porto landmark layer for the game")
    ap.add_argument("--data", type=Path, default=DATA_DEFAULT)
    ap.add_argument("--out", type=Path, default=OUT_DEFAULT)
    args = ap.parse_args(argv)
    try:
        layer = build(args.data)
    except (OSError, KeyError, ValueError) as err:
        print(f"landmarks error: {err}", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(render_js(layer).encode("utf-8"))
    print(f"wrote {args.out} ({len(layer['items'])} landmarks)")  # type: ignore[arg-type]
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
