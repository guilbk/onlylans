"""Building footprints for the game map (GAME MODEL decoration, not UCI data).

Lots are laid on a grid per district, dropped when too close to a road of ``game/roads.json``
(or in water or a park) and typed by the district polygon of :mod:`pipeline.basemap`. Everything
is seeded by position, so the output bytes are identical between runs. Result:
``game/src/js/37_buildings_data.js`` (``PG.buildings``).
Each building is 8 whole numbers in ``b``: x, y, width, height (m), rotation (deg), district id,
colour index, roof shape. ``trees`` is a flat ``[x, y, ...]`` list.

Dense Porto blocks: ``rows`` holds terraced rows that run wall to wall along both sides of every
street. A row is 6 whole numbers: x, y (start of its centre line, m), length (m), rotation (deg),
depth (m), district id. The client cuts a row into houses; the rows never touch a street, the
river, a park or a landmark, and thin out with the distance from the centre.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

from pipeline import basemap, landmarks
from pipeline.basemap import Pt, inside_poly, to_m
from pipeline.landmarks import DATA_DEFAULT, map_size_m

ROADS_DEFAULT = Path("game/roads.json")
OUT_DEFAULT = Path("game/src/js/37_buildings_data.js")
HEADER = "// generated by pipeline/buildings.py, do not edit\n"
CAP = 6000
ROAD_HALF_M = 6.0  # road half-width, metres
MARGIN_M = 3.0
CELL = 60.0  # road index cell, metres
GENERIC_REACH_M = 55.0  # outside named districts, build only this close to a road

# district ids (index into the JS palettes)
RIBEIRA, BAIXA, BOAVISTA, FOZ, MATOSINHOS, CAMPANHA, BONFIM, OTHER = range(8)
# roof shapes
FLAT, HIP, COURT, LSHAPE, VILLA, SHED, CRANE = range(7)
NAMES = {"Ribeira": RIBEIRA, "Baixa": BAIXA, "Boavista": BOAVISTA, "Matosinhos": MATOSINHOS,
         "Campanhã": CAMPANHA, "Bonfim": BONFIM}  # fmt: skip
FOZ_LONLAT = ((-8.6820, 41.1480), (-8.6650, 41.1470), (-8.6600, 41.1560), (-8.6780, 41.1620),
              (-8.6830, 41.1550))  # fmt: skip
# block (rotation cell) size and gap between lots, metres
BLOCK = {BAIXA: 72, BOAVISTA: 120, FOZ: 90, MATOSINHOS: 110, CAMPANHA: 96, BONFIM: 84, OTHER: 120}
GAP = {BAIXA: 3, BOAVISTA: 22, FOZ: 34, MATOSINHOS: 14, CAMPANHA: 18, BONFIM: 6, OTHER: 12}
# grid step per district, metres
STEP = {RIBEIRA: 10, BAIXA: 22, BOAVISTA: 62, FOZ: 40, MATOSINHOS: 40, CAMPANHA: 56, BONFIM: 36,
        OTHER: 90}  # fmt: skip
Seg = tuple[float, float, float, float]
CELL_M = 6.0  # house width unit along a street; rows are runs of whole cells
DEPTHS = (
    70.0,
    55.0,
    46.0,
    38.0,
    30.0,
    23.0,
    17.0,
    13.0,
    10.0,
    7.5,
    5.0,
)  # deepest first; the street grid is wide, so rows fill the block
EDGE_DEPTH = 17.0  # thin zones build only this deep
EDGE_GAP_M = 0.8  # clearance between a row and the next street's edge
CAP_ROWS = 9000
MAX_RUN = 20  # cells per row, so a row stays inside the client's culling tile (120 m)
DENSE_KM = 1.7  # fully built within this distance of the centre (Baixa), thinner beyond
THIN_KM = 6.0  # beyond this only a sparse fringe is built
LM_CLEAR = {"square": 70.0, "market": 40.0, "station": 45.0, "cathedral": 40.0, "palace": 40.0}
LM_CLEAR_DEFAULT = 22.0


def hsh(ix: int, iy: int, salt: int = 0) -> float:
    """Deterministic hash of a grid cell.

    Args:
        ix: Cell x.
        iy: Cell y.
        salt: Stream selector.

    Returns:
        A float in [0, 1).
    """
    h = (ix * 73856093 ^ iy * 19349663 ^ salt * 83492791) & 0xFFFFFFFF
    h = ((h ^ (h >> 15)) * 2246822519) & 0xFFFFFFFF
    h = ((h ^ (h >> 13)) * 3266489917) & 0xFFFFFFFF
    return (h ^ (h >> 16)) / 4294967296.0


def bank_y(poly: list[Pt], x: float) -> float | None:
    """Northern (smallest y) crossing of a polygon with the vertical line at ``x``.

    Args:
        poly: Polygon vertices.
        x: Line position.

    Returns:
        The y of the crossing, or None when the line misses the polygon.
    """
    ys = [
        a[1] + (x - a[0]) / (b[0] - a[0]) * (b[1] - a[1])
        for a, b in zip(poly, poly[-1:] + poly[:-1], strict=True)
        if (a[0] <= x) != (b[0] <= x)
    ]
    return min(ys) if ys else None


def load_segments(path: Path) -> list[Seg]:
    """Read the road graph as straight segments in metres.

    Args:
        path: ``roads.json``.

    Returns:
        ``(x0, y0, x1, y1)`` per polyline piece.
    """
    d = json.loads(path.read_text(encoding="utf-8"))
    u = float(d["unit_m"])
    segs: list[Seg] = []
    for e in d["edges"]:
        p = e[2]
        for i in range(0, len(p) - 2, 2):
            segs.append((p[i] * u, p[i + 1] * u, p[i + 2] * u, p[i + 3] * u))
    return segs


def seg_dist(px: float, py: float, s: Seg) -> float:
    """Distance from a point to a segment.

    Args:
        px: Point x.
        py: Point y.
        s: The segment.

    Returns:
        Metres.
    """
    x0, y0, x1, y1 = s
    dx, dy = x1 - x0, y1 - y0
    ln = dx * dx + dy * dy
    t = 0.0 if ln == 0 else max(0.0, min(1.0, ((px - x0) * dx + (py - y0) * dy) / ln))
    return math.hypot(px - x0 - t * dx, py - y0 - t * dy)


def index_segments(segs: list[Seg]) -> dict[tuple[int, int], list[int]]:
    """Bucket segments into a grid of ``CELL`` metres (bounding-box cells).

    Args:
        segs: Road segments.

    Returns:
        Map cell to segment ids.
    """
    grid: dict[tuple[int, int], list[int]] = {}
    for i, (x0, y0, x1, y1) in enumerate(segs):
        for cx in range(int(min(x0, x1) // CELL), int(max(x0, x1) // CELL) + 1):
            for cy in range(int(min(y0, y1) // CELL), int(max(y0, y1) // CELL) + 1):
                grid.setdefault((cx, cy), []).append(i)
    return grid


def nearest(
    x: float, y: float, segs: list[Seg], grid: dict[tuple[int, int], list[int]]
) -> tuple[float, int]:
    """Nearest road around a point (3x3 cells, so exact below ``CELL`` metres).

    Args:
        x: Point x.
        y: Point y.
        segs: Road segments.
        grid: Result of :func:`index_segments`.

    Returns:
        ``(distance, segment id)``; id is -1 when no road is near.
    """
    cx, cy = int(x // CELL), int(y // CELL)
    best, bi = math.inf, -1
    for gx in (cx - 1, cx, cx + 1):
        for gy in (cy - 1, cy, cy + 1):
            for i in grid.get((gx, gy), ()):
                d = seg_dist(x, y, segs[i])
                if d < best:
                    best, bi = d, i
    return best, bi


def size_for(d: int, kind: float, r1: float, r2: float) -> tuple[float, float, int, int]:
    """Pick footprint size, colour and roof for a lot.

    Args:
        d: District id.
        kind: Hash selecting a sub-type.
        r1: Hash for size.
        r2: Hash for colour.

    Returns:
        ``(width, height, colour index, roof)``.
    """
    c = int(r2 * 6)
    if d == RIBEIRA:
        return 5 + 2 * r1, 10 + 6 * r1, c, HIP if kind < 0.7 else FLAT
    if d == BAIXA:
        return (
            18 + 8 * r1,
            18 + 8 * r2,
            c % 3,
            COURT if kind < 0.3 else FLAT if kind < 0.6 else HIP,
        )
    if d == BOAVISTA:
        if kind < 0.35:
            return 20 + 10 * r1, 20 + 10 * r1, c % 4, LSHAPE
        if kind < 0.7:
            return 16 + 10 * r1, 40 + 20 * r2, c % 4, FLAT
        return 24 + 8 * r1, 24, c % 4, FLAT
    if d == FOZ:
        return 10 + 4 * r1, 9 + 4 * r2, c % 3, VILLA
    if d == MATOSINHOS:
        return 18 + 14 * r1, 60 + 40 * r2, c % 3, SHED
    if d == CAMPANHA:
        if kind < 0.3:
            return 14 + 6 * r1, 70 + 40 * r2, c % 3, SHED
        return 14 + 6 * r1, 18 + 8 * r2, c % 4, HIP if kind < 0.6 else FLAT
    if d == BONFIM:
        return 13 + 6 * r1, 15 + 8 * r2, c % 4, HIP if kind < 0.5 else FLAT
    return 9 + 5 * r1, 11 + 6 * r2, c % 4, HIP if kind < 0.6 else FLAT


def build(data_path: Path = DATA_DEFAULT, roads_path: Path = ROADS_DEFAULT) -> dict[str, object]:
    """Lay out the buildings and trees.

    Args:
        data_path: ``game_data.json`` (map size).
        roads_path: ``roads.json``.

    Returns:
        JSON-ready dict with ``source``, ``b`` and ``trees``.
    """
    w, h = map_size_m(data_path)
    segs = load_segments(roads_path)
    grid = index_segments(segs)
    lay = basemap.build(data_path)

    def polys(flat_polys: list[list[int]]) -> list[list[Pt]]:
        """Flat coordinate lists to point polygons."""
        return [[(p[i], p[i + 1]) for i in range(0, len(p), 2)] for p in flat_polys if p]

    water = polys([lay["river"], lay["sea"]])  # type: ignore[list-item]
    parks = polys([p["poly"] for p in lay["parks"]])  # type: ignore[index,union-attr]
    dists = lay["districts"]  # type: ignore[assignment]
    zones = list(
        zip((NAMES[d["name"]] for d in dists), polys([d["poly"] for d in dists]), strict=True)
    )  # type: ignore[index]
    zones.insert(0, (FOZ, basemap.clip_poly([to_m(*q) for q in FOZ_LONLAT], w, h)))
    mat = next(pl for d, pl in zones if d == MATOSINHOS)
    out: list[tuple[int, ...]] = []
    trees: list[int] = []
    rib = next(pl for d, pl in zones if d == RIBEIRA)
    riv = water[0]

    def ok_spot(x: float, y: float, need: float, polys_d: list[list[Pt]], other: bool) -> bool:
        """Lot centre is on land, in its district, off the parks and clear of roads."""
        if not (0 <= x <= w and 0 <= y <= h):
            return False
        if other and any(inside_poly((x, y), pl) for _, pl in zones):
            return False
        if not other and polys_d and not any(inside_poly((x, y), pl) for pl in polys_d):
            return False
        if any(inside_poly((x, y), pl) for pl in water):
            return False
        if any(inside_poly((x, y), pl) for pl in parks):
            return False
        dist, si = nearest(x, y, segs, grid)
        return si >= 0 and dist >= need and not (other and dist > GENERIC_REACH_M)

    # Ribeira: one tidy row of narrow facades on the quay (two rows deep), along the river bank
    xs = [p[0] for p in rib]
    for n, x in enumerate(range(int(min(xs)), int(max(xs)), 7)):
        ya, yb = bank_y(riv, x - 4), bank_y(riv, x + 4)
        if ya is None or yb is None:
            continue
        ang = round(math.degrees(math.atan2(yb - ya, 8))) % 180
        for row, (off, bh) in enumerate(((15, 11), (32, 14))):
            y = (ya + yb) / 2 - off
            if not ok_spot(x, y, 4.0, [], False) or any(inside_poly((x, y), pl) for pl in parks):
                continue
            col = (n * 3 + row + int(hsh(x, row, 8) * 2)) % 4
            out.append((x, round(y), 6, bh, ang, RIBEIRA, col, HIP))
    mat_xs = [p[0] for p in mat]
    port_x = min(mat_xs) + 0.45 * (max(mat_xs) - min(mat_xs))
    for d in (BAIXA, BOAVISTA, FOZ, MATOSINHOS, CAMPANHA, BONFIM, OTHER):
        s = BLOCK[d]
        polys_d = [] if d == OTHER else [pl for z, pl in zones if z == d]
        if d != OTHER and not polys_d:
            continue
        bx = [p[0] for pl in polys_d for p in pl] or [0, w]
        by = [p[1] for pl in polys_d for p in pl] or [0, h]
        for cy in range(int(min(by) // s), int(max(by) // s) + 1):
            for cx in range(int(min(bx) // s), int(max(bx) // s) + 1):
                px, py = (cx + 0.5) * s, (cy + 0.5) * s
                dist, si = nearest(px, py, segs, grid)
                if si < 0:
                    continue
                kind, r1, r2 = hsh(cx, cy, 4), hsh(cx, cy, 5), hsh(cx, cy, 6)
                bw, bh, _, roof0 = size_for(d, kind, r1, r2)
                if d == MATOSINHOS and px > port_x:
                    bw, bh, roof0 = 13 + 5 * r1, 16 + 6 * r2, HIP  # town houses east of the port
                bw, bh = round(bw), round(bh)
                x0, y0, x1, y1 = segs[si]
                ang = round(math.degrees(math.atan2(y1 - y0, x1 - x0))) % 180
                ca, sa = math.cos(math.radians(ang)), math.sin(math.radians(ang))
                pu, pv = bw + GAP[d], bh + GAP[d]
                r = math.hypot(bw, bh) / 2
                c0 = int(hsh(cx, cy, 7) * 2)
                nu, nv = int(s / pu) + 1, int(s / pv) + 1
                for i in range(-nu, nu + 1):
                    for j in range(-nv, nv + 1):
                        lx, ly = i * pu, j * pv
                        x, y = px + lx * ca - ly * sa, py + lx * sa + ly * ca
                        if abs(x - px) > s / 2 - r * 0.5 or abs(y - py) > s / 2 - r * 0.5:
                            continue
                        if not ok_spot(x, y, r + ROAD_HALF_M + MARGIN_M, polys_d, d == OTHER):
                            continue
                        hl = hsh(round(x), round(y), 3)
                        if d == FOZ and hl < 0.35:
                            continue  # sparse villas
                        col = 2 if hl < 0.12 else c0
                        roof = roof0
                        if roof0 in (HIP, FLAT) and hl > 0.8:
                            roof = FLAT if roof0 == HIP else HIP
                        out.append((round(x), round(y), bw, bh, ang, d, col, roof))
    out = [
        b for b in out if b[5] == FOZ or (b[5] == MATOSINHOS and b[0] <= port_x) or b[5] == RIBEIRA
    ]  # keep villas, the port sheds and the quay row; terraces come from the rows below
    lms = [
        (*landmarks.project(lm), LM_CLEAR.get(lm.kind, LM_CLEAR_DEFAULT))
        for lm in landmarks.LANDMARKS
    ]
    baixa = next(pl for d, pl in zones if d == BAIXA)
    cx0 = sum(q[0] for q in baixa) / len(baixa)
    cy0 = sum(q[1] for q in baixa) / len(baixa)
    dense_zones = [pl for d, pl in zones if d in (RIBEIRA, BAIXA, BONFIM)]

    def dry(x: float, y: float) -> bool:
        """Point is on land, off parks and clear of landmarks."""
        if not (0 <= x <= w and 0 <= y <= h):
            return False
        if any(math.hypot(x - lx, y - ly) < r for lx, ly, r in lms):
            return False
        return not any(inside_poly((x, y), pl) for pl in water + parks)

    def free(x: float, y: float) -> bool:
        """Point is dry and clear of every street."""
        return nearest(x, y, segs, grid)[0] >= ROAD_HALF_M + EDGE_GAP_M and dry(x, y)

    def density(x: float, y: float) -> float:
        """Share of the street front that is built here: 1 in the old centre, less outside."""
        if any(inside_poly((x, y), pl) for pl in dense_zones):
            return 1.0
        km = math.hypot(x - cx0, y - cy0) / 1000.0
        if km <= DENSE_KM:
            return 1.0
        return max(0.12, 0.85 * (1 - (km - DENSE_KM) / (THIN_KM - DENSE_KM)))

    def zone_of(x: float, y: float) -> int:
        """District id of a point (OTHER outside every polygon)."""
        return next((d for d, pl in zones if inside_poly((x, y), pl)), OTHER)

    rows: list[tuple[int, int, int, int, int, int]] = []

    def close(run: list[int], depth: float, geo: tuple[float, ...]) -> None:
        """Turn a run of street cells into one row (dropped in the villa / port-shed zones)."""
        if not run:
            return
        x0, y0, ux, uy, nx, ny, ang, flip = geo
        off = ROAD_HALF_M + EDGE_GAP_M + depth / 2
        ln = len(run) * CELL_M
        px = x0 + ux * run[0] * CELL_M + nx * off
        py = y0 + uy * run[0] * CELL_M + ny * off
        mx, my = px + ux * ln / 2, py + uy * ln / 2
        d = zone_of(mx, my)
        run.clear()
        if d == FOZ or (d == MATOSINHOS and mx <= port_x):
            return
        if d == OTHER and math.hypot(mx - cx0, my - cy0) < 2500:
            d = BONFIM
        if flip:  # start from the far end so the row runs along its stored angle
            px, py = px + ux * ln, py + uy * ln
        rows.append((round(px), round(py), round(ln), int(ang), round(depth), d))

    for si, (x0, y0, x1, y1) in enumerate(segs):
        ln = math.hypot(x1 - x0, y1 - y0)
        if ln < CELL_M:
            continue
        ux, uy = (x1 - x0) / ln, (y1 - y0) / ln
        deg = round(math.degrees(math.atan2(uy, ux)))
        ang, flip = deg % 180, not 0 <= deg < 180  # a row always runs along +angle
        n = int(ln // CELL_M)
        for side in (1, -1):
            nx, ny = -uy * side, ux * side
            run: list[int] = []
            run_depth = 0.0
            geo = (x0, y0, ux, uy, nx, ny, ang, flip)

            for c in range(n):
                t0 = c * CELL_M
                mx, my = x0 + ux * (t0 + CELL_M / 2), y0 + uy * (t0 + CELL_M / 2)
                if hsh(si, c // 5, 11 + side) > density(mx, my):
                    close(run, run_depth, geo)
                    continue
                got = 0.0
                es = (-CELL_M / 2 + 1, 0.0, CELL_M / 2 - 1)
                dens = density(mx, my)
                for dep in DEPTHS:
                    if dep > EDGE_DEPTH and dens < 1.0:
                        continue
                    off = ROAD_HALF_M + EDGE_GAP_M
                    m = math.ceil(dep / 8.0)  # sample every <= 8 m across the strip
                    pts = [off + dep * i / m for i in range(1, m + 1)]
                    if all(dry(mx + nx * off + ux * e, my + ny * off + uy * e) for e in es) and all(
                        free(mx + nx * o + ux * e, my + ny * o + uy * e) for o in pts for e in es
                    ):
                        got = dep
                        break
                if not got or (run and (got != run_depth or len(run) >= MAX_RUN)):
                    close(run, run_depth, geo)
                if got:
                    run_depth = got
                    run.append(c)
            close(run, run_depth, geo)
    if len(rows) > CAP_ROWS:
        rows.sort(key=lambda r: hsh(r[0], r[1], 12))
        rows = rows[:CAP_ROWS]
    rows.sort(key=lambda r: (r[1], r[0]))
    for p in lay["parks"]:  # type: ignore[union-attr]
        pl = [(p["poly"][i], p["poly"][i + 1]) for i in range(0, len(p["poly"]), 2)]  # type: ignore[index]
        for ty in range(int(min(q[1] for q in pl) // 22), int(max(q[1] for q in pl) // 22) + 1):
            for tx in range(int(min(q[0] for q in pl) // 22), int(max(q[0] for q in pl) // 22) + 1):
                x, y = (tx + hsh(tx, ty, 1)) * 22, (ty + hsh(tx, ty, 2)) * 22
                if hsh(tx, ty, 3) < 0.3 and inside_poly((x, y), pl):
                    trees += [round(x), round(y)]
    if len(out) > CAP:  # keep the named districts, thin the rest by hash
        keep = [b for b in out if b[5] != OTHER]
        rest = sorted((b for b in out if b[5] == OTHER), key=lambda b: hsh(b[0], b[1], 9))
        out = (keep + rest)[:CAP]
    out.sort(key=lambda b: (b[1], b[0]))
    return {
        "source": basemap.SOURCE,
        "b": [v for b in out for v in b],
        "rows": [v for r in rows for v in r],
        "trees": trees[:3000],
    }


def render_js(layer: dict[str, object]) -> str:
    """Render the layer as the generated JS data file (deterministic).

    Args:
        layer: Result of :func:`build`.

    Returns:
        JS source with sorted keys and LF line ends.
    """
    body = json.dumps(layer, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return f"{HEADER}window.PG = window.PG || {{}};\nPG.buildings = {body};\n"


def main(argv: list[str] | None = None) -> int:
    """Command line entry point.

    Args:
        argv: Arguments (default ``sys.argv[1:]``).

    Returns:
        0 on success, 1 when an input cannot be read.
    """
    ap = argparse.ArgumentParser(description="Write the Porto building footprints for the game")
    ap.add_argument("--data", type=Path, default=DATA_DEFAULT)
    ap.add_argument("--roads", type=Path, default=ROADS_DEFAULT)
    ap.add_argument("--out", type=Path, default=OUT_DEFAULT)
    args = ap.parse_args(argv)
    try:
        layer = build(args.data, args.roads)
    except (OSError, KeyError, ValueError) as err:
        print(f"buildings error: {err}", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(render_js(layer).encode("utf-8"))
    print(f"wrote {args.out} ({len(layer['b']) // 8} buildings)")  # type: ignore[arg-type]
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
