def smooth(pts: list[tuple[float, ...]], n: int = 8) -> list[tuple[float, ...]]:
    """Catmull-Rom subdivision of a polyline (passes through every input point).

    Args:
        pts: Input points, any equal tuple length.
        n: Pieces per input span.

    Returns:
        The denser, smooth polyline.
    """
    out: list[tuple[float, ...]] = []
    for i in range(len(pts) - 1):
        p0, p1, p2, p3 = pts[max(i - 1, 0)], pts[i], pts[i + 1], pts[min(i + 2, len(pts) - 1)]
        for k in range(n):
            t = k / n
            out.append(tuple(
                0.5 * (2 * b + (-a + c) * t + (2 * a - 5 * b + 4 * c - d) * t * t
                       + (-a + 3 * b - 3 * c + d) * t**3)
                for a, b, c, d in zip(p0, p1, p2, p3, strict=True)
            ))  # fmt: skip
    out.append(pts[-1])
    return out


def to_m(lon: float, lat: float) -> Pt:
    """Project lon/lat to map metres.

    Args:
        lon: Longitude, degrees.
        lat: Latitude, degrees.

    Returns:
        ``(x, y)`` metres in the map frame.
    """
    return geo.proj(lon, lat)


def clip_poly(poly: list[Pt], w: float, h: float) -> list[Pt]:
    """Clip a polygon to the rectangle ``[0, w] x [0, h]`` (Sutherland-Hodgman).

    Args:
        poly: Polygon vertices, metres.
        w: Map width, metres.
        h: Map height, metres.

    Returns:
        The clipped polygon, empty when nothing is left.
    """
    edges = (
        (lambda p: p[0], 0.0, True), (lambda p: p[0], w, False),
        (lambda p: p[1], 0.0, True), (lambda p: p[1], h, False),
    )  # fmt: skip
    out = poly
    for axis, lim, keep_ge in edges:
        src, out = out, []
        for i, cur in enumerate(src):
            prev = src[i - 1]
            c_in = axis(cur) >= lim if keep_ge else axis(cur) <= lim
            p_in = axis(prev) >= lim if keep_ge else axis(prev) <= lim
            if c_in != p_in:
                t = (lim - axis(prev)) / (axis(cur) - axis(prev))
                out.append((prev[0] + t * (cur[0] - prev[0]), prev[1] + t * (cur[1] - prev[1])))
            if c_in:
                out.append(cur)
    return out


def flat(poly: list[Pt]) -> list[int]:
    """Flatten points to whole metres ``[x0, y0, x1, y1, ...]``.

    Args:
        poly: Points, metres.

    Returns:
        The rounded flat list.
    """
    return [round(v) for p in poly for v in p]


def river_polygon() -> list[Pt]:
    """Build the Douro polygon: both banks offset from the centre line, simplified.

    Returns:
        Polygon in metres (north bank west-to-east is reversed: south bank first), unclipped.
    """
    c = [(*to_m(lon, lat), min(max(wd, 200), 290) / 2) for lon, lat, wd in smooth(list(DOURO))]
    north: list[Pt] = []
    south: list[Pt] = []
    for i, (x, y, hw) in enumerate(c):
        ax, ay, _ = c[max(i - 1, 0)]
        bx, by, _ = c[min(i + 1, len(c) - 1)]
        d = math.hypot(bx - ax, by - ay) or 1.0
        nx, ny = (by - ay) / d, -(bx - ax) / d  # unit normal
        wob = 1 + 0.07 * math.sin(i * 1.3), 1 + 0.07 * math.sin(i * 1.9 + 2)  # irregular banks
        north.append((x + nx * hw * wob[0], y + ny * hw * wob[0]))
        south.append((x - nx * hw * wob[1], y - ny * hw * wob[1]))
    if north[0][1] > south[0][1]:  # make "north" the bank with the smaller y
        north, south = south, north
    return geo.rdp(north, SIMPLIFY_M) + geo.rdp(south, SIMPLIFY_M)[::-1]


def sea_polygon(h: float) -> list[Pt]:
    """Build the Atlantic polygon: everything west of the coast line.

    Args:
        h: Map height, metres.

    Returns:
        Polygon in metres, unclipped (its west edge lies far outside the map).
    """
    coast = geo.rdp([to_m(*p) for p in smooth(list(COAST))], SIMPLIFY_M)
    return [(-500.0, -500.0), *coast, (-500.0, h + 500.0)][::1]


def river_at(lon: float) -> tuple[float, float, float]:
    """Interpolate the (smoothed) river centre line at a longitude.

    Args:
        lon: Longitude, degrees (inside the line's range).

    Returns:
        ``(x, y, half width)`` in metres.
    """
    pts = smooth(list(DOURO))[::-1]  # west to east, increasing lon
    for a, b in zip(pts, pts[1:], strict=False):
        if a[0] <= lon <= b[0]:
            t = (lon - a[0]) / (b[0] - a[0])
            x, y = to_m(lon, a[1] + t * (b[1] - a[1]))
            return x, y, (min(max(a[2] + t * (b[2] - a[2]), 200), 290)) / 2
    raise ValueError(f"longitude {lon} is outside the river")


def bridge_line(lon: float, extra: float) -> list[Pt]:
    """Make a short deck across the river at a longitude, square to the river.

    Args:
        lon: Longitude where the bridge crosses the centre line.
        extra: Metres added beyond each bank.

    Returns:
        Two end points in metres.
    """
    x, y, hw = river_at(lon)
    ax, ay, _ = river_at(lon - 0.0006)
    bx, by, _ = river_at(lon + 0.0006)
    d = math.hypot(bx - ax, by - ay) or 1.0
    nx, ny = -(by - ay) / d, (bx - ax) / d
    r = hw * 1.07 + extra
    return [(x - nx * r, y - ny * r), (x + nx * r, y + ny * r)]


def inside_poly(p: Pt, poly: list[Pt]) -> bool:
    """Ray-casting point-in-polygon test.

    Args:
        p: The point.
        poly: Polygon vertices.

    Returns:
        True when the point is inside.
    """
    hit = False
    for i, a in enumerate(poly):
        b = poly[i - 1]
        if (a[1] > p[1]) != (b[1] > p[1]) and p[0] < (b[0] - a[0]) * (p[1] - a[1]) / (
            b[1] - a[1]
        ) + a[0]:
            hit = not hit
    return hit


def build(data_path: Path = DATA_DEFAULT) -> dict[str, object]:
    """Compute the base map layer, clipped to the map.

    Args:
        data_path: ``game_data.json`` (for the map size).

    Returns:
        JSON-ready dict with ``source``, ``river``, ``sea``, ``parks``, ``districts``, ``bridges``.
    """
    w, h = map_size_m(data_path)

    def clipped(poly: list[Pt]) -> list[int]:
        """Clip to the map and flatten."""
        return flat(clip_poly(poly, w, h))

    districts = []
    for name, outline in (*DISTRICTS, ("Foz", FOZ_LONLAT)):
        poly = clip_poly([to_m(*q) for q in outline], w, h)
        if poly:
            cx = sum(q[0] for q in poly) / len(poly)
            cy = sum(q[1] for q in poly) / len(poly)
            districts.append({"name": name, "ua": DISTRICT_UA[name], "x": round(cx), "y": round(cy), "poly": flat(poly)})
    parks = [{"name": n, "poly": clipped([to_m(*p) for p in poly])} for n, poly in PARKS]
    bridges = [
        {
            "name": n,
            "arch": int(n in ARCHED),
            "line": flat(clip_poly_line(bridge_line(lon, ex), w, h)),
        }
        for n, lon, ex in BRIDGES
    ]
    return {
        "source": SOURCE,
        "river": clipped(river_polygon()),
        "sea": clipped(sea_polygon(h)),
        "parks": [p for p in parks if p["poly"]],
        "districts": districts,
        "bridges": [b for b in bridges if b["line"]],
    }


def clip_poly_line(line: list[Pt], w: float, h: float) -> list[Pt]:
    """Keep a short line only if both ends are inside the map (bridges are never cut).

    Args:
        line: End points, metres.
        w: Map width.
        h: Map height.

    Returns:
        The line, or an empty list when an end is outside.
    """
    return line if all(0 <= x <= w and 0 <= y <= h for x, y in line) else []


def render_js(layer: dict[str, object]) -> str:
    """Render the layer as the generated JS data file (deterministic).

    Args:
        layer: Result of :func:`build`.

    Returns:
        JS source with sorted keys and LF line ends.
    """
    body = json.dumps(layer, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return f"{HEADER}window.PG = window.PG || {{}};\nPG.basemap = {body};\n"


def main(argv: list[str] | None = None) -> int:
    """Command line entry point.

    Args:
        argv: Arguments (default ``sys.argv[1:]``).

    Returns:
        0 on success, 1 when the data file cannot be read.
    """
    ap = argparse.ArgumentParser(description="Write the Porto base map layer for the game")
    ap.add_argument("--data", type=Path, default=DATA_DEFAULT)
    ap.add_argument("--out", type=Path, default=OUT_DEFAULT)
    args = ap.parse_args(argv)
    try:
        layer = build(args.data)
    except (OSError, KeyError, ValueError) as err:
        print(f"basemap error: {err}", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(render_js(layer).encode("utf-8"))
    print(f"wrote {args.out} ({len(layer['districts'])} districts)")  # type: ignore[arg-type]
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
