import json
from pathlib import Path

from pipeline import geo, landmarks

DATA = Path("game/game_data.json")


def test_projection_of_known_point():
    lm = landmarks.Landmark("t", "T", "T", "tower", geo.LON0 + 0.01, geo.LAT0 - 0.01, 0)
    assert landmarks.project(lm) == (round(0.01 * geo.M_LON), round(0.01 * geo.M_LAT))


def test_bounds_filtering(monkeypatch):
    far = landmarks.Landmark("far", "Far", "Far", "tower", 0.0, 0.0, 0)
    monkeypatch.setattr(landmarks, "LANDMARKS", (*landmarks.LANDMARKS, far))
    ids = [i["id"] for i in landmarks.build(DATA)["items"]]
    assert "far" not in ids
    assert len(ids) == len(landmarks.LANDMARKS) - 1
    assert not landmarks.inside((-1, 5), (15000, 19000))


def test_all_shipped_landmarks_are_on_the_map():
    assert len(landmarks.build(DATA)["items"]) == len(landmarks.LANDMARKS)
    assert {lm.kind for lm in landmarks.LANDMARKS} <= set(landmarks.KINDS)


def test_labels_do_not_overlap():
    boxes = []
    for it in landmarks.build(DATA)["items"]:
        w = len(it["label"]) * landmarks.CHAR_PX + 6
        x0 = {"l": it["lx"], "r": it["lx"] - w, "c": it["lx"] - w / 2}[it["align"]]
        base = (it["x"] * landmarks.REF_K, it["y"] * landmarks.REF_K)
        y1 = it["ly"] + 3
        boxes.append(landmarks.shifted((x0, y1 - landmarks.LABEL_H, x0 + w, y1), *base))
        boxes.append(landmarks.shifted(landmarks.GLYPH, *base))
    for i, a in enumerate(boxes):
        for j, b in enumerate(boxes):
            if i < j and i // 2 != j // 2 and (i % 2 == 0 or j % 2 == 0):  # two glyphs may touch
                assert not landmarks.overlaps(a, b), (i // 2, j // 2)


def test_deterministic_output():
    a = landmarks.render_js(landmarks.build(DATA))
    assert a == landmarks.render_js(landmarks.build(DATA))
    assert a.startswith("// generated by pipeline/landmarks.py, do not edit")
    assert "not from the UCI" in a


def test_main_writes_file(tmp_path):
    out = tmp_path / "l.js"
    assert landmarks.main(["--data", str(DATA), "--out", str(out)]) == 0
    text = out.read_text(encoding="utf-8")
    obj = json.loads(text.split("PG.landmarks = ", 1)[1].rsplit(";", 1)[0])
    assert obj["items"][0]["id"] == "clerigos"
